#!/usr/bin/env python3
"""
gen_icons.py - convert RetroArch XMB (monochrome) PNG icons into C arrays
(RGB565A, little-endian) embedded in xmb_assets.h for the custom launcher.

Two sizes per category (active is bigger/brighter, inactive smaller/dimmer),
statically emulating the XMB scale/brightness emphasis (no runtime scaling).

Icons: libretro/retroarch-assets, xmb/monochrome/png/*.png  (CC-BY-4.0)
Run:  python3 gen_icons.py
"""
import os
from PIL import Image

HERE   = os.path.dirname(os.path.abspath(__file__))   # launcher/tools
ROOT   = os.path.dirname(HERE)                        # launcher/
SRCDIR = os.path.join(ROOT, "assets", "ra")
OUT    = os.path.join(ROOT, "xmb_assets.h")

# category -> retroarch monochrome icon name
CATS = [("image", "image"), ("music", "music"), ("menu_video", "menu_video"),
        ("core", "core"), ("folder", "folder"), ("setting", "setting")]
# variant, tint colour, pixel size (all same base size; active only ~12% bigger)
VARIANTS = [("hi", (255, 255, 255), 46),   # active: slightly larger, white
            ("lo", (150, 162, 196), 40)]   # inactive: base size, dim


def encode(path, color, size):
    im = Image.open(path).convert("RGBA").resize((size, size), Image.LANCZOS)
    av = im.split()[3].load()
    r5 = (color[0] >> 3) & 0x1F
    g6 = (color[1] >> 2) & 0x3F
    b5 = (color[2] >> 3) & 0x1F
    rgb = (r5 << 11) | (g6 << 5) | b5
    lo, hi = rgb & 0xFF, (rgb >> 8) & 0xFF
    out = bytearray()
    for y in range(size):
        for x in range(size):
            out += bytes((lo, hi, av[x, y]))
    return bytes(out)


def carr(name, data):
    lines = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join(str(v) for v in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "/* AUTO-GENERATED by gen_icons.py - do not edit.",
        " * Icons (c) libretro/retroarch-assets, xmb/monochrome (CC-BY-4.0).",
        " * Format: RGB565A, little-endian: [rgb565_lo, rgb565_hi, alpha] per pixel.",
        " */",
        "#ifndef __XMB_ASSETS_H__",
        "#define __XMB_ASSETS_H__",
        "",
        "typedef struct { const unsigned char *px; short w; short h; } xmb_icon_t;",
        "",
    ]
    rows_hi, rows_lo = [], []
    for icon, _ in CATS:
        p = os.path.join(SRCDIR, icon + ".png")
        if not os.path.exists(p):
            print("missing", p)
            continue
        for var, col, size in VARIANTS:
            name = f"xmb_ic_{icon}_{var}"
            parts.append(carr(name, encode(p, col, size)))
            parts.append("")
            row = f"{{ {name}, {size}, {size} }}"
            (rows_hi if var == "hi" else rows_lo).append(row)
    parts.append("static const xmb_icon_t xmb_cat_icon_hi[] = { "
                 + ", ".join(rows_hi) + " };")
    parts.append("static const xmb_icon_t xmb_cat_icon_lo[] = { "
                 + ", ".join(rows_lo) + " };")
    parts.append(f"#define XMB_CAT_ICON_COUNT {len(rows_hi)}")
    parts.append("")
    parts.append("#endif /* __XMB_ASSETS_H__ */")
    open(OUT, "w").write("\n".join(parts) + "\n")
    print("wrote", OUT, os.path.getsize(OUT), "bytes,", len(rows_hi), "icons")


if __name__ == "__main__":
    main()
